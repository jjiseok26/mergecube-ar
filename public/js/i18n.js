  function current() {
    const saved = localStorage.getItem(KEY);
    return text[saved] ? saved : "ko";
  }

  function t(key, vars) {
    const pack = text[current()] || text.ko;
    let value = pack[key] ?? text.ko[key] ?? key;
    if (vars) {
      for (const [name, piece] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, piece);
    }
    return value;
  }

  function apply(root = document) {
    const lang = current();
    document.documentElement.lang = lang;
    const titleKey = document.body?.dataset.i18nTitle;
    if (titleKey) document.title = t(titleKey);
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.dataset.i18nAria));
    });
    root.querySelectorAll("[data-lang-select]").forEach((select) => {
      select.value = lang;
    });
  }

  function setLang(lang) {
    localStorage.setItem(KEY, text[lang] ? lang : "ko");
    apply();
    window.dispatchEvent(new CustomEvent("langchange"));
  }

  document.addEventListener("change", (event) => {
    const select = event.target.closest?.("[data-lang-select]");
    if (!select) return;
    setLang(select.value);
  });

  window.I18N = { t, apply, setLang, current };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", () => apply());
  else apply();
